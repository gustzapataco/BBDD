-- TABLA COMUNA.
CREATE TABLE comuna (
id_comuna      NUMBER(3),
id_region      NUMBER(2) NOT NULL,
nombre_comuna  VARCHAR2(40) NOT NULL,

CONSTRAINT pk_comuna
PRIMARY KEY (id_comuna),

CONSTRAINT fk_comuna_region
FOREIGN KEY (id_region)
REFERENCES region (id_region)
);

-- TABLA TRABAJADOR.
CREATE TABLE trabajador (
codigo_inscripcion  NUMBER(10),
rut                 NUMBER(8) NOT NULL,
digito_verificador  CHAR(1) NOT NULL,
nombres             VARCHAR2(50) NOT NULL,
apellidos           VARCHAR2(60) NOT NULL,
sueldo_base         NUMBER(10) NOT NULL,
fecha_nacimiento    DATE NOT NULL,
genero              CHAR(1) NOT NULL,
estado_civil        VARCHAR2(20) NOT NULL,
telefono_movil      VARCHAR2(15) NOT NULL,
direccion           VARCHAR2(100) NOT NULL,
email               VARCHAR2(80),
id_comuna           NUMBER(3) NOT NULL,
id_nacionalidad     NUMBER NOT NULL,

CONSTRAINT pk_trabajador
PRIMARY KEY (codigo_inscripcion),

CONSTRAINT un_trabajador_rut
UNIQUE (rut),

CONSTRAINT fk_trabajador_comuna
FOREIGN KEY (id_comuna)
REFERENCES comuna (id_comuna),

CONSTRAINT fk_trabajador_nacionalidad
FOREIGN KEY (id_nacionalidad)
REFERENCES nacionalidad (id_nacionalidad)
);

-- TABLA JUGADOR_FUTBOL.
CREATE TABLE jugador_futbol (
codigo_inscripcion       NUMBER(10),
id_asociacion            NUMBER(3) NOT NULL,
id_escuela               NUMBER(4),
puesto_campo             VARCHAR2(30) NOT NULL,
monto_total_premios      NUMBER(12) NOT NULL,
anio_dejo_amateurismo    NUMBER(4),

CONSTRAINT pk_jugador_futbol
PRIMARY KEY (codigo_inscripcion),

CONSTRAINT fk_jugador_trabajador
FOREIGN KEY (codigo_inscripcion)
REFERENCES trabajador (codigo_inscripcion),

CONSTRAINT fk_jugador_asociacion
FOREIGN KEY (id_asociacion)
REFERENCES asociacion (id_asociacion),

CONSTRAINT fk_jugador_escuela
FOREIGN KEY (id_escuela)
REFERENCES escuela_futbol (id_escuela)
);

-- TABLA PERSONAL_PLANTA.
CREATE TABLE personal_planta (
codigo_inscripcion        NUMBER(10),
id_club                   NUMBER(3) NOT NULL,
cantidad_horas_trabajadas NUMBER(5),
valor_horas_extras        NUMBER(10),

CONSTRAINT pk_personal_planta
PRIMARY KEY (codigo_inscripcion),

CONSTRAINT fk_personal_trabajador
FOREIGN KEY (codigo_inscripcion)
REFERENCES trabajador (codigo_inscripcion),

CONSTRAINT fk_personal_club
FOREIGN KEY (id_club)
REFERENCES club_futbol (id_club)
);

-- TABLA CONTRATO.
CREATE TABLE contrato (
codigo_inscripcion  NUMBER(10),
id_club             NUMBER(3),
fecha_inicio        DATE,
fecha_termino       DATE,

CONSTRAINT pk_contrato
PRIMARY KEY (
codigo_inscripcion,
id_club,
fecha_inicio
),

CONSTRAINT fk_contrato_jugador
FOREIGN KEY (codigo_inscripcion)
REFERENCES jugador_futbol (codigo_inscripcion),

CONSTRAINT fk_contrato_club
FOREIGN KEY (id_club)
REFERENCES club_futbol (id_club)
);

-- TABLA JUGADOR_IDIOMA.
CREATE TABLE jugador_idioma (
codigo_inscripcion  NUMBER(10),
id_idioma           NUMBER(3),
nivel_dominio       VARCHAR2(20) NOT NULL,

CONSTRAINT pk_jugador_idioma
PRIMARY KEY (
codigo_inscripcion,
id_idioma
),

CONSTRAINT fk_jug_idioma_jugador
FOREIGN KEY (codigo_inscripcion)
REFERENCES jugador_futbol (codigo_inscripcion),

CONSTRAINT fk_jug_idioma_idioma
FOREIGN KEY (id_idioma)
REFERENCES idioma (id_idioma)
);

