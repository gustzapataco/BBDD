-- TABLA REGION.
CREATE TABLE region (
id_region     NUMBER(2),
nombre_region VARCHAR2(60) NOT NULL,

CONSTRAINT pk_region
PRIMARY KEY (id_region)
);

-- TABLA NACIONALIDAD.
CREATE TABLE nacionalidad (
id_nacionalidad NUMBER
GENERATED BY DEFAULT AS IDENTITY (START WITH 210 INCREMENT BY 2),
descripcion VARCHAR2(30) NOT NULL,

CONSTRAINT pk_nacionalidad
PRIMARY KEY (id_nacionalidad)
);

-- TABLA ASOCIACION.
CREATE TABLE asociacion (
id_asociacion       NUMBER(3),
nombre_asociacion   VARCHAR2(80) NOT NULL,
fecha_creacion      DATE NOT NULL,
tipo_asociacion     CHAR(1) NOT NULL,

CONSTRAINT pk_asociacion
PRIMARY KEY (id_asociacion),

CONSTRAINT ck_asociacion_fecha
CHECK (fecha_creacion >= DATE '1980-12-31'),

CONSTRAINT ck_asociacion_tipo
CHECK (tipo_asociacion IN ('P', 'A'))
);

-- TABLA ESCUELA_FUTBOL.
CREATE TABLE escuela_futbol (
id_escuela       NUMBER(4),
nombre_escuela   VARCHAR2(60) NOT NULL,
capacidad        NUMBER(5) NOT NULL,
fecha_fundacion  DATE NOT NULL,

CONSTRAINT pk_escuela_futbol
PRIMARY KEY (id_escuela)
);

-- TABLA IDIOMA.
CREATE TABLE idioma (
id_idioma       NUMBER(3),
nombre_idioma   VARCHAR2(30) NOT NULL,

CONSTRAINT pk_idioma
PRIMARY KEY (id_idioma)
);

-- TABLA CLUB_FUTBOL.
CREATE TABLE club_futbol (
id_club          NUMBER(3),
nombre_club      VARCHAR2(60) NOT NULL,
patrimonio       NUMBER(12) NOT NULL,
ubicacion_calle  VARCHAR2(100) NOT NULL,

CONSTRAINT pk_club_futbol
PRIMARY KEY (id_club),

CONSTRAINT un_club_futbol_nombre
UNIQUE (nombre_club)
);

/*
==============================================
 DDL: MODIFICACION
 2. Modificar una tabla mediante ALTER TABLE.
==============================================
*/

ALTER TABLE club_futbol
ADD tipo_club VARCHAR2(15)
DEFAULT 'Profesional'
NOT NULL;

